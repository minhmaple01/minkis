export function getCharacterInfo(charTag: string): CharacterInfo {
  // Normalize tag
  const cleaned = charTag.replace(/^\[char-/, "").replace(/\]$/, "").trim();
  const normalizedKey = cleaned.replace(/\s+/g, "_");

  if (FIXED_CHARACTERS[normalizedKey]) {
    return FIXED_CHARACTERS[normalizedKey];
  }

  // Check case-insensitive
  for (const [key, val] of Object.entries(FIXED_CHARACTERS)) {
    if (key.toLowerCase() === normalizedKey.toLowerCase() || val.name.toLowerCase() === normalizedKey.toLowerCase()) {
      return val;
    }
  }

  // Fallback guest character
  const displayName = cleaned.replace(/_/g, " ");
  return {
    id: cleaned.toLowerCase(),
    name: displayName,
    tag: cleaned,
    age: "Character",
    relation: "Guest character",
    personality: "Guest in the story",
    role: "Guest",
    avatarEmoji: "✨",
    badgeBg: "bg-neutral-500/10",
    badgeBorder: "border-neutral-400/30",
    badgeText: "text-neutral-700 dark:text-neutral-300",
    bubbleBg: "bg-neutral-50/60 dark:bg-neutral-900/40",
    bubbleBorder: "border-neutral-200 dark:border-neutral-800",
    voicePitch: 1.0,
    voiceRate: 0.95,
  };
}
